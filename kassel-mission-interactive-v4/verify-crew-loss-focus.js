const assert=require('node:assert/strict'),focus=require('./crew-loss-focus.js'),stations=require('./crew-stations.js');
const data={pilot:'Example'},pilot={n:'Pilot',r:'Pilot'},copilot={n:'Copilot',r:'Co-Pilot'};
const roster={Example:[pilot,copilot]},site={x:3,y:0,z:5};
const plane={visible:true,position:{x:1,y:100,z:2},userData:{planeData:data,v2:{sitePos:site}}};
const state={_crewLossHandoff:true,crewPos:'pilot'};
const buddy={plane:data,member:copilot,sp:{visible:true,position:{x:4,y:50,z:6}}};
assert.equal(focus.select(plane,state,roster,[buddy],stations.resolve).kind,'aircraft');
const own={plane:data,member:pilot,sp:{visible:true,position:{x:5,y:80,z:7}}};
const selected=focus.select(plane,state,roster,[buddy,own],stations.resolve);
assert.equal(selected.kind,'airman');assert.equal(selected.position,own.sp.position);assert.equal(selected.member,pilot);
plane.visible=false;
assert.equal(focus.select(plane,state,roster,[buddy],stations.resolve).position,site,'No switching to another airman after impact');
assert.equal(focus.select(plane,state,roster,[own],stations.resolve).kind,'airman');
own.sp.visible=false;
assert.equal(focus.select(plane,state,roster,[own],stations.resolve).kind,'impact');
state.crewPos='copilot';plane.visible=true;
assert.equal(focus.select(plane,state,roster,[buddy],stations.resolve).member,copilot);
assert.equal(focus.select(null,state,roster,[],stations.resolve),null);
console.log('PASS: same-aircraft/airman handoff before impact, no buddy substitution, hidden-chute exclusion, crew switching and impact fallback. Camera selection logic only, not full browser verification.');
