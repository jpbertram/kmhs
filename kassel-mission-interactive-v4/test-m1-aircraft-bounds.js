'use strict';
const assert=require('node:assert/strict');
const T=require('../tmp/three-r128.js'),api=require('./aircraft-map-scale');
const plane=new T.Group();
plane.add(new T.Mesh(new T.BoxGeometry(10,2,30),new T.MeshBasicMaterial()));
const before=api.fit(T,plane,30,1);
const room=new T.Group();
room.userData.rebuiltInterior=true;
room.add(new T.Mesh(new T.BoxGeometry(15,8,40),new T.MeshBasicMaterial()));
plane.add(room);
assert.equal(api.fit(T,plane,30,1),before,'Changing camera must not refit aircraft scale or ground support');
assert.equal(plane.scale.x,1);
assert.equal(api.supportDepth(plane),1);
console.log('PASS aircraft bounds: cockpit attachment cannot change map scale or ground support');
plane.rotation.x=.4;
plane.position.y=.2;
const ground=(x,z)=>2+.05*z;
api.clearTerrain(T,plane,ground);
const bounds=api.orientedBounds(T,plane);
const extent=(axis)=>bounds.half.reduce((sum,half,i)=>sum+half*Math.abs(bounds.axes[i][axis]),0);
assert(bounds.centre.y-extent('y')>=ground(bounds.centre.x,bounds.centre.z+extent('z'))-1e-10);
console.log('PASS aircraft bounds: banked aircraft clears sloped terrain across its footprint');
