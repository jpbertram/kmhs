const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const smoke=require('./loss-smoke.js'),timeline=require('./mission-timeline.js'),trajectory=require('./loss-trajectory.js');
const v={beh:'fall',ft:20,dur:180,style:2,seed:123,profile:{motion:'burning_glide'},startPos:{x:0,y:115,z:0},ctrl:{x:50,y:100,z:30},sitePos:{x:100,y:8,z:50},fwd:{x:1,y:0,z:0},escapeAcross:{x:0,y:0,z:1},escapeAmt:12};
assert.equal(smoke.sample([v],160,timeline,trajectory).length,0,'No smoke before attack');
const birth=timeline.playbackAtBattleCue(v.ft),impact=timeline.playbackAtBattleCue(v.ft+v.dur);
assert.equal(smoke.sample([v],birth-.01,timeline,trajectory).length,0,'No emission before loss event');
const initial=JSON.stringify(v),at=birth+8;
const first=smoke.sample([v],at,timeline,trajectory);
assert(first.length>0);assert(first.length<=38);
assert(first.every(p=>Object.values(p).every(Number.isFinite)));
assert.deepEqual(smoke.sample([v],at,timeline,trajectory),first,'Pause must leave identical trail positions');
smoke.sample([v],at+10,timeline,trajectory);
assert.deepEqual(smoke.sample([v],at,timeline,trajectory),first,'Seek backward must reconstruct original trail');
assert.equal(JSON.stringify(v),initial,'Sampling must not mutate aircraft state');
assert.equal(smoke.sample([v],impact+14,timeline,trajectory).length,0,'Airborne trail expires after impact; no new emissions');
const many=Array.from({length:25},(_,i)=>({...v,seed:i}));
assert(smoke.sample(many,at,timeline,trajectory).length<=1100,'Complete loss roster fits dedicated pool');
for(let cue=0;cue<700;cue++)assert(Math.abs(timeline.battleCueAtPlayback(timeline.playbackAtBattleCue(cue))-cue)<1e-6);
const code=fs.readFileSync(path.join(__dirname,'km3d-v3.js'),'utf8');
assert(code.includes('KasselLossSmoke.sample(lossStates,smokeTime,KMMissionTimeline,KasselLossTrajectory,true)'));
const aftermath=smoke.sample([v],impact+14,timeline,trajectory,true);
assert(aftermath.length>0,'Ground plume persists after airborne trail expires');
assert(aftermath.every(p=>p.y>=v.sitePos.y+1.5));
assert.deepEqual(smoke.sample([v],impact+14,timeline,trajectory,true),aftermath,'Ground plume pause and seek are repeatable');
assert(smoke.sample(many,impact+14,timeline,trajectory,true).length<=1100,'Combined plume fits existing pool');
assert(!code.includes('emitPool(KM._smoke,x+(Math.random()-.5)*2,y+1,z+(Math.random()-.5)*2)'));
assert.throws(()=>smoke.sample([v],NaN,timeline,trajectory));
console.log('PASS: pre-damage exclusion, repeat/pause/seek determinism, source-state immutability, impact expiry, 25-plane capacity and 700 cue inversions. Visual reconstruction only, not smoke-fluid validation.');
