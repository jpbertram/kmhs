// Finds every instrument dial in a crew-station GLB from its gauge-atlas UVs and
// writes their position, facing, size and instrument type for cockpit-live.js.
// Rerun whenever the station models are re-exported:
//   node tools/cockpit-live/extract-gauges.mjs tools/crew-stations/flightdeck-plain.glb --labels b24-cockpit.html > cockpit-gauges.js
// Atlas contract (b24-cockpit.html): 8x8 cells; cell c holds gaugeDefs[c % gaugeDefs.length].
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const base=new URL('../crew-stations/node_modules/@gltf-transform/',import.meta.url);
const {NodeIO}=await import(new URL('core/dist/index.js',base));
const {ALL_EXTENSIONS}=await import(new URL('extensions/dist/index.js',base));
const LABELS=['AIR SPEED','ALTITUDE','GYRO HORIZON','TURN','DIRECTIONAL GYRO','RATE OF CLIMB','MANIFOLD PRESS','TACHOMETER','FUEL PRESS','OIL TEMP','OIL PRESS','CYL. TEMP','CARB. AIR','CLOCK','SUCTION','FUEL','AMPERES','FLAPS','HYD. PRESS','FREE AIR'];
const file=process.argv[2];
// the face labels, in atlas order, from the cockpit page when given (--labels b24-cockpit.html)
const li=process.argv.indexOf('--labels');
if(li>0){const fs=await import('node:fs');const html=fs.readFileSync(process.argv[li+1],'utf8');const block=html.slice(html.indexOf('const gaugeDefs'),html.indexOf('];',html.indexOf('const gaugeDefs')));LABELS.length=0;for(const m of block.matchAll(/G\('([^']+)'/g))LABELS.push(m[1]);}const flipV=process.argv.includes('--flip-v');
const doc=await new NodeIO().registerExtensions(ALL_EXTENSIONS).read(file);
const sub=(a,b)=>[a[0]-b[0],a[1]-b[1],a[2]-b[2]],cross=(a,b)=>[a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]];
const len=a=>Math.hypot(...a),norm=a=>{const l=len(a)||1;return a.map(v=>v/l);};
function xf(m,p){return [m[0]*p[0]+m[4]*p[1]+m[8]*p[2]+m[12],m[1]*p[0]+m[5]*p[1]+m[9]*p[2]+m[13],m[2]*p[0]+m[6]*p[1]+m[10]*p[2]+m[14]];}
const tris=[];
for(const node of doc.getRoot().listNodes()){
 const mesh=node.getMesh();if(!mesh)continue;const W=node.getWorldMatrix();
 for(const prim of mesh.listPrimitives()){
  const mat=prim.getMaterial();if(!mat||!/gauge/i.test(mat.getName()))continue;
  const P=prim.getAttribute('POSITION'),U=prim.getAttribute('TEXCOORD_0'),I=prim.getIndices();
  const n=I?I.getCount():P.getCount(),e=[];
  for(let t=0;t<n;t+=3){const v=[0,1,2].map(k=>{const i=I?I.getScalar(t+k):t+k;return {p:xf(W,P.getElement(i,[])),uv:U.getElement(i,[])};});tris.push(v);}
 }
}
// connected dials: triangles of one atlas cell that share vertices
const key=p=>p.map(v=>Math.round(v*2000)).join(','),parent=tris.map((_,i)=>i),find=i=>parent[i]===i?i:(parent[i]=find(parent[i]));
const cellOf=t=>{const u=(t[0].uv[0]+t[1].uv[0]+t[2].uv[0])/3,v=(t[0].uv[1]+t[1].uv[1]+t[2].uv[1])/3;
 return (flipV?Math.floor(v*8):Math.floor((1-v)*8))*8+Math.floor(u*8);};
const seen=new Map();
tris.forEach((t,i)=>{const c=cellOf(t);t.cell=c;for(const q of t){const k=c+'|'+key(q.p);if(seen.has(k))parent[find(i)]=find(seen.get(k));else seen.set(k,i);}});
const gm=new Map();tris.forEach((t,i)=>{const r=find(i);if(!gm.has(r))gm.set(r,{cell:t.cell,tris:[]});gm.get(r).tris.push(t);});
const groups=[...gm.values()];
const out=[];
for(const g of groups){
 const pts=g.tris.flat();let ctr=[0,0,0];pts.forEach(q=>{ctr=ctr.map((v,i)=>v+q.p[i]);});ctr=ctr.map(v=>v/pts.length);
 let nrm=[0,0,0];g.tris.forEach(t=>{const c=cross(sub(t[1].p,t[0].p),sub(t[2].p,t[0].p));nrm=nrm.map((v,i)=>v+c[i]);});nrm=norm(nrm);
 const r=Math.max(...pts.map(q=>len(sub(q.p,ctr))))/0.94*0.86/0.92;   // dial radius in metres (face ring ~0.86 of cell)
 // dial "up" = direction of increasing canvas-up (v up in three's flipY convention)
 const t=g.tris[0],e1=sub(t[1].p,t[0].p),e2=sub(t[2].p,t[0].p),du1=t[1].uv[0]-t[0].uv[0],dv1=t[1].uv[1]-t[0].uv[1],du2=t[2].uv[0]-t[0].uv[0],dv2=t[2].uv[1]-t[0].uv[1];
 const det=du1*dv2-du2*dv1||1e-9,s=flipV?-1:1;
 const up=norm(e1.map((v,i)=>s*(-du2*v+du1*e2[i])/det));
 out.push({label:LABELS[g.cell%LABELS.length],cell:g.cell,c:ctr.map(v=>+v.toFixed(4)),n:nrm.map(v=>+v.toFixed(4)),up:up.map(v=>+v.toFixed(4)),r:+(Math.max(...pts.map(q=>len(sub(q.p,ctr))))).toFixed(4)});
}
out.sort((a,b)=>a.c[2]-b.c[2]||a.c[0]-b.c[0]);
console.log('/* Generated by tools/cockpit-live/extract-gauges.mjs from '+file.split('/').pop()+'. Frame: crew GLB metres, +Y up, nose -Z. */');
console.log('(function(root){root.KasselCockpitGauges='+JSON.stringify(out)+';if(typeof module!=="undefined")module.exports=root.KasselCockpitGauges;})(typeof window!=="undefined"?window:globalThis);');
