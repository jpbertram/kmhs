'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const T=require('../tmp/three-r128.js');
const src=fs.readFileSync(__dirname+'/km3d-v3.js','utf8');
const ctx={V2:{_hiddenOwnShip:[]},KM:{_crewPositions:{pilot:{},copilot:{},nav:{},radio:{}}},THREE:T,console:{warn(){}}};
let builds=0,fail=false;
ctx.window={KasselInterior:{build(){
  if(fail)throw Error('Injected cabin failure');
  builds++;
  const group=new T.Group();
  group.userData.rebuiltInterior=true;
  return {group,seats:{}};
}}};
vm.runInNewContext(src.slice(src.indexOf('V2.attachInterior=function'),src.indexOf('V2.updateStationOverlay=function')),ctx);
const plane=new T.Group(), exterior=new T.Group();plane.add(exterior);
const state=ctx.KM._camState={mode:'crew',crewPos:'pilot',selectedPlane:plane};
ctx.V2.attachInterior();
const cockpit=plane.children[1];
state.crewPos='copilot';ctx.V2.attachInterior();
assert.equal(builds,1,'Both seats must share one flight deck');
assert.equal(plane.children[1],cockpit);
const other=new T.Group(),otherExterior=new T.Group();other.add(otherExterior);
state.crewPos='nav';fail=true;
assert.equal(ctx.V2.attachInterior(other),false);
assert.equal(cockpit.parent,plane);
assert(otherExterior.visible);
fail=false;ctx.V2.attachInterior(other);
assert(exterior.visible);
assert(!otherExterior.visible);
state.crewPos='pilot';ctx.V2.attachInterior(other);
assert.equal(cockpit.parent,other);
assert.equal(builds,2);
state.mode='orbit';ctx.V2.attachInterior();
assert(otherExterior.visible);
assert.equal(cockpit.parent,null);
console.log('PASS cabin cache: shared seats, safe failure, reattachment and exterior restoration');
